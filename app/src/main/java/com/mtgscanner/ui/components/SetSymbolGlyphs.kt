    private val glyphs: Map<String, Int> by lazy {
        PACKED.split(' ').filter { it.isNotEmpty() }.associate { pair ->
            val (code, hex) = pair.split('=')
            code to hex.toInt(16)
        }
    }

    /**
     * The glyph for a Scryfall set code, or null when the font has none. Promo and token sets
     * ("plci", "tlci") fall back to their parent set's symbol.
     */
    fun glyph(code: String?): String? {
        val c = code?.trim()?.lowercase().orEmpty()
        if (c.isEmpty()) return null
        val cp = glyphs[c]
            ?: c.takeIf { it.length == 4 && it[0] in "pt" }?.let { glyphs[it.drop(1)] }
            ?: return null
        return String(Character.toChars(cp))
    }

    /** How many set codes the font knows. */
    val count: Int get() = glyphs.size
